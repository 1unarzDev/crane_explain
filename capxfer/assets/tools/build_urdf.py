"""Generate the capxfer square-module URDFs from module_budget.py and the STEP wheel geometry (WS-H).

Run from capxfer/:  .venv/bin/python assets/tools/build_urdf.py
Writes assets/urdf/module_{lidar,cam}[_lifter].urdf (wheel joints, no roller links) and
assets/urdf/module_lidar_rollers.urdf (same, plus 9 passive roller links per wheel).
All values are ESTIMATES (see docs/HARDWARE_ESTIMATES.md); regenerate after measurement.
"""
import json, math, os, runpy, sys, io, contextlib
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
with contextlib.redirect_stdout(io.StringIO()):
    B = runpy.run_path(os.path.join(HERE, "module_budget.py"))
S, R, WW, LX, LY = B["S"], B["R"], B["WW"], B["LX"], B["LY"]
CLEAR, TOP = B["CLEAR"], B["TOP"]
OUT = os.path.join(os.path.dirname(HERE), "urdf")

# STEP-derived roller geometry (assets/wheel_step_geometry.json)
N_ROLL, ROLL_ANG = 9, math.radians(45.0)
ROLL_RC = 0.038693        # roller centre radius
ROLL_L, ROLL_D = 0.04418, 0.018722
ROLL_M = 9.679e-6 * 1200  # 9679 mm^3 PU (1.2 g/cm3)  -> 11.6 g
ROLL_IAX, ROLL_ITR = 3.674487e-7 * 1.2, 1.464053e-6 * 1.2   # mm^5 * 1.2e-6 kg/mm^3 -> kg m^2
# helix sign of the vendor STEP wheel = -1 => bottom roller "\" seen from above. Mirror => "/".
PATTERN = {"fl": "/", "fr": "\\", "rl": "\\", "rr": "/"}   # params/module_measured.yaml convention
HELIX = {"/": +1, "\\": -1}
SIGN = {"fl": (1, 1), "fr": (1, -1), "rl": (-1, 1), "rr": (-1, -1)}

def f(x): return " ".join(f"{v:.6g}" for v in x)

def inertial(m, com, I):
    return (f'    <inertial><origin xyz="{f(com)}" rpy="0 0 0"/><mass value="{m:.5g}"/>'
            f'<inertia ixx="{I[0][0]:.6g}" ixy="{I[0][1]:.6g}" ixz="{I[0][2]:.6g}" iyy="{I[1][1]:.6g}" iyz="{I[1][2]:.6g}" izz="{I[2][2]:.6g}"/></inertial>\n')

def rpy_from_z_to(v):
    """rpy rotating local +z onto unit vector v (for URDF cylinders)."""
    v = np.asarray(v, float) / np.linalg.norm(v)
    pitch = math.atan2(math.hypot(v[0], v[1]), v[2]); yaw = math.atan2(v[1], v[0])
    return (0.0, pitch, yaw)

def body_parts(sens, lift):
    extra = B["SENS"][sens] + ([B["LIFTER"]] if lift else [])
    parts = B["C"] + [(a, b, np.array(c, float), d, e, g) for a, b, c, d, e, g in extra]
    return [p for p in parts if not p[0].startswith("wheel_") and p[0] != "lifter_arm_stowed"]

def build(sens, lift, rollers=False):
    name = f"capxfer_module_{sens}{'_lifter' if lift else ''}{'_rollers' if rollers else ''}"
    m, cg, I, _ = B["summarize"](body_parts(sens, lift))
    zb = R   # base_link sits at axle height above base_footprint
    L = []
    L.append('<?xml version="1.0"?>\n')
    L.append(f'''<!-- {name}: GENERATED by assets/tools/build_urdf.py (WS-H). ESTIMATES ONLY - every number is datasheet, STEP-derived
     or estimated (docs/HARDWARE_ESTIMATES.md); nothing is measured. Regenerate after the T0 measurements.
     Frames: REP-103 (x forward, y left, z up). base_footprint = module centre on the floor; base_link = module centre at axle height.
     Square module side {S} m; wheels at (+-{LX}, +-{LY}) m; wheel radius {R} m (STEP OD 96.1 mm, unloaded).
     MECANUM MODEL. Wheel joints are continuous about +y (child frame y = axle). Contact-roller axis per corner, seen from above with
     the module front up (params convention): fl "/", fr "\\", rl "\\", rr "/". The vendor STEP wheel as drawn is a "\\" wheel
     (bottom roller axis along (1,1)/sqrt2); fl and rr use the mirrored part. Traction is transmitted only along the contact-roller
     axis a_i; perpendicular to it the roller rolls freely. Simulators: (a) capxfer/sim.py uses a_i directly (assembly.r_hat);
     (b) physics engines without rollers: anisotropic friction with mu along a_i and mu2 ~ 0.0-0.05 perpendicular (fdir1 = a_i);
     (c) module_*_rollers.urdf has {N_ROLL} passive roller links per wheel (continuous joints along the roller axis, barrel approximated
     by a cylinder {ROLL_L*1000:.1f} mm x {ROLL_D*1000:.1f} mm; use a capsule/ellipsoid or mesh in engines where the cylinder edge snags).
     Each wheel link comment repeats its pattern. The lifter arm design is unknown: it is a single fixed stowed mass (lifter variants).
     Docking frames dock_<face>: origin on the face plane at magnet height, +x = outward normal. -->
<robot name="{name}">
  <link name="base_footprint"/>
  <joint name="base_footprint_joint" type="fixed"><parent link="base_footprint"/><child link="base_link"/><origin xyz="0 0 {zb:.5f}" rpy="0 0 0"/></joint>
  <link name="base_link">
''')
    L.append(inertial(m, cg - np.array([0, 0, zb]), I))
    hc = TOP - CLEAR; zc = (TOP + CLEAR) / 2 - zb
    L.append(f'    <visual><origin xyz="0 0 {zc:.4f}" rpy="0 0 0"/><geometry><box size="{S} {S} {hc:.3f}"/></geometry><material name="petg"><color rgba="0.2 0.22 0.25 1"/></material></visual>\n')
    # collision: chassis box minus wheel wells is approximated by a central box + two end slabs (wheels sit in side wells)
    inner_y = 2 * (LY - WW / 2 - 0.004)
    L.append(f'    <collision name="chassis_core"><origin xyz="0 0 {zc:.4f}" rpy="0 0 0"/><geometry><box size="{S} {inner_y:.4f} {hc:.3f}"/></geometry></collision>\n')
    xs = S - 2 * (LX + R + 0.004)
    for sgn in (1, -1):
        L.append(f'    <collision name="side_bridge_{"l" if sgn>0 else "r"}"><origin xyz="0 {sgn*(S/2 - (S/2-inner_y/2)/2):.4f} {zc:.4f}" rpy="0 0 0"/><geometry><box size="{xs:.4f} {S/2-inner_y/2:.4f} {hc:.3f}"/></geometry></collision>\n')
    if sens == "lidar":
        L.append(f'    <collision name="lidar_col"><origin xyz="-0.05 0 {TOP+0.0207-zb:.4f}" rpy="0 0 0"/><geometry><box size="0.0556 0.0556 0.0413"/></geometry></collision>\n')
    L.append('  </link>\n')
    # wheels
    m_w = B["WHEEL_M"] - (N_ROLL * ROLL_M if rollers else 0.0)
    Iax = B["WHEEL_IAX"] - (N_ROLL * (ROLL_M * ROLL_RC**2 + 0.5 * (ROLL_IAX + ROLL_ITR)) if rollers else 0.0)
    for cn in ("fl", "fr", "rl", "rr"):
        sx, sy = SIGN[cn]; pat = PATTERN[cn]; h = HELIX[pat]
        Iw = [[0.5 * Iax + m_w * WW**2 / 12, 0, 0], [0, Iax, 0], [0, 0, 0.5 * Iax + m_w * WW**2 / 12]]
        L.append(f'  <!-- wheel_{cn}: contact roller "{pat}" ({"mirrored STEP part" if pat == "/" else "STEP part as drawn"}); '
                 f'traction axis a = ({1/math.sqrt(2):.4f}, {(-1 if pat=="/" else 1)/math.sqrt(2):.4f}) in the module frame -->\n')
        L.append(f'  <link name="wheel_{cn}_link">\n' + inertial(m_w, [0, 0, 0], Iw))
        L.append(f'    <visual><origin xyz="0 0 0" rpy="1.5707963 0 0"/><geometry><cylinder radius="{R:.5f}" length="{WW-0.008:.3f}"/></geometry><material name="roller"><color rgba="0.35 0.35 0.33 1"/></material></visual>\n')
        if not rollers:
            L.append(f'    <collision><origin xyz="0 0 0" rpy="1.5707963 0 0"/><geometry><cylinder radius="{R:.5f}" length="0.0404"/></geometry></collision>\n')
        L.append('  </link>\n')
        L.append(f'  <joint name="wheel_{cn}_joint" type="continuous"><parent link="base_link"/><child link="wheel_{cn}_link"/>'
                 f'<origin xyz="{sx*LX:.4f} {sy*LY:.4f} 0" rpy="0 0 0"/><axis xyz="0 1 0"/>'
                 f'<limit effort="3.33" velocity="10.47"/><dynamics damping="0.0" friction="0.0"/></joint>\n')
        if rollers:
            a = np.array([0, 1.0, 0])
            for k in range(N_ROLL):
                phi = 2 * math.pi * k / N_ROLL
                rhat = np.array([math.sin(phi), 0, -math.cos(phi)])   # k=0 at the bottom
                t = np.cross(a, rhat)
                # helix sign h: (ra.a)(ra.t) has sign h
                ra = (math.cos(ROLL_ANG) * a + h * math.sin(ROLL_ANG) * t); ra /= np.linalg.norm(ra)
                c = ROLL_RC * rhat
                rpy = rpy_from_z_to(ra)
                Ir = [[ROLL_ITR, 0, 0], [0, ROLL_ITR, 0], [0, 0, ROLL_IAX]]
                L.append(f'  <link name="roller_{cn}_{k}">\n' + inertial(ROLL_M, [0, 0, 0], Ir))
                L.append(f'    <collision><origin xyz="0 0 0" rpy="0 0 0"/><geometry><cylinder radius="{ROLL_D/2:.5f}" length="{ROLL_L:.5f}"/></geometry></collision>\n  </link>\n')
                L.append(f'  <joint name="roller_{cn}_{k}_joint" type="continuous"><parent link="wheel_{cn}_link"/><child link="roller_{cn}_{k}"/>'
                         f'<origin xyz="{f(c)}" rpy="{f(rpy)}"/><axis xyz="0 0 1"/><dynamics damping="1e-5" friction="0.0"/></joint>\n')
    # docking faces
    zd = 0.060 - zb
    for face, (x, y, yaw) in {"front": (S/2, 0, 0), "left": (0, S/2, math.pi/2), "rear": (-S/2, 0, math.pi), "right": (0, -S/2, -math.pi/2)}.items():
        L.append(f'  <link name="dock_{face}"/><joint name="dock_{face}_joint" type="fixed"><parent link="base_link"/><child link="dock_{face}"/>'
                 f'<origin xyz="{x:.4f} {y:.4f} {zd:.4f}" rpy="0 0 {yaw:.7f}"/></joint>\n')
    # sensors and boards (frames only; masses are in base_link)
    frames = [("imu_link", (0.0, 0.0, 0.075)), ("pico_link", (0.0, 0.05, 0.075))]
    if sens == "lidar":
        frames += [("laser_link", (-0.05, 0, TOP + 0.03)), ("d435_link", (S/2 - 0.015, 0, 0.125)), ("compute_opi5pro", (-0.06, -0.06, 0.088))]
    else:
        frames += [("ov9282_link", (S/2 - 0.012, 0, 0.115)), ("compute_opi4pro", (-0.06, -0.06, 0.088))]
    for n, p in frames:
        L.append(f'  <link name="{n}"/><joint name="{n}_joint" type="fixed"><parent link="base_link"/><child link="{n}"/><origin xyz="{p[0]:.4f} {p[1]:.4f} {p[2]-zb:.4f}" rpy="0 0 0"/></joint>\n')
    cam = "d435_link" if sens == "lidar" else "ov9282_link"
    L.append(f'  <link name="{cam.replace("_link","")}_optical_frame"/><joint name="{cam}_optical_joint" type="fixed"><parent link="{cam}"/>'
             f'<child link="{cam.replace("_link","")}_optical_frame"/><origin xyz="0 0 0" rpy="-1.5707963 0 -1.5707963"/></joint>\n')
    if lift:
        nm, ml, pl, Il, _, _ = B["LIFTER"]
        L.append(f'  <!-- lifter arm: design unknown; stowed lumped mass {ml} kg (estimate 0.30-0.80). Replace with real links when the design is known. -->\n')
        L.append(f'  <link name="lifter_arm">\n' + inertial(ml, [0, 0, 0], Il.tolist()))
        L.append(f'    <collision><origin xyz="0 0 0" rpy="0 0 0"/><geometry><box size="0.12 0.10 0.10"/></geometry></collision>\n  </link>\n')
        L.append(f'  <joint name="lifter_mount" type="fixed"><parent link="base_link"/><child link="lifter_arm"/><origin xyz="{pl[0]} {pl[1]} {pl[2]-zb:.4f}" rpy="0 0 0"/></joint>\n')
    L.append('</robot>\n')
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name.replace("capxfer_", "") + ".urdf")
    open(path, "w").write("".join(L))
    return path

if __name__ == "__main__":
    for sens in ("lidar", "cam"):
        for lift in (False, True):
            print(build(sens, lift))
    print(build("lidar", False, rollers=True))
