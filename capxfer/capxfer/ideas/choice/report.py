"""CHOICE: markdown tables from results.json / demo_results.json -> ~/.cache/capxfer/CHOICE/tables.md (SIMULATION).

  PYTHONPATH=. .venv/bin/python -m capxfer.ideas.choice.report
"""
from __future__ import annotations

import json
import pathlib

OUT = pathlib.Path.home() / ".cache/capxfer/CHOICE"
POL = ("cert", "bb", "healthy", "random", "probe_all", "oracle")
NAME = dict(cert="certificate (pre-split)", bb="black-box carry-over", healthy="assume healthy", random="random",
            probe_all="split, then probe all (P2)", oracle="oracle")


def f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def main():
    R = json.loads((OUT / "results.json").read_text())
    T = R["tables"]
    L = ["# CHOICE tables (SIMULATION; generated by capxfer.ideas.choice.report)", ""]
    L += [f"constants: {json.dumps(R['constants'])}", ""]
    L += ["## Dock success vs true strafe ratio z (narrow bay, closed loop, omni planner)", "",
          "| z bin | n | dock success |", "|---|---|---|"]
    L += [f"| [{b['lo']}, {b['hi']}) | {b['n']} | {f(b['success'], 2)} |" for b in R["dock_by_z"]]
    L += ["", f"proxy agreement (z >= tau vs dock success): {R['proxy_agreement']}", "",
          "demo fault kinds (direct dock sims): " + json.dumps(R["dock_demo_kinds"]), ""]
    for alpha in ("0.1", "0.05"):
        for tau in ("0.5", "0.8", "0.9"):
            L += [f"## alpha = {alpha}, tau = {tau} (3,000 faulted test episodes, 600 per size 2-6)", "",
                  "| policy | dock success, 1st dispatch [95% CI] | unsafe dispatch [95% CI] | abstain | missed | "
                  "mission success | time / success (s) | mean time (s) |", "|---|---|---|---|---|---|---|---|"]
            for p in POL:
                s, m = T[f"{alpha}|{tau}|{p}"]["single_shot"], T[f"{alpha}|{tau}|{p}"]["mission"]
                L.append(f"| {NAME[p]} | {f(s['success'])} [{f(s['success_ci'][0])}, {f(s['success_ci'][1])}] | "
                         f"{f(s['unsafe'])} [{f(s['unsafe_ci'][0])}, {f(s['unsafe_ci'][1])}] | {f(s['abstain'])} | "
                         f"{f(s['missed'])} | {f(m['final_success'])} | {f(m['time_per_success'], 1)} | "
                         f"{f(m['mean_time'], 1)} |")
            L += ["", "by size (success / unsafe / abstain):", "",
                  "| policy | " + " | ".join(f"{n} mod" for n in range(2, 7)) + " |", "|---" * 6 + "|"]
            for p in POL:
                L.append(f"| {NAME[p]} | " + " | ".join(
                    "{:.2f} / {:.3f} / {:.2f}".format(*(T[f"{alpha}|{tau}|{p}"][f"nmod{n}"]["single_shot"][k]
                                                        for k in ("success", "unsafe", "abstain")))
                    for n in range(2, 7)) + " |")
            fts = sorted(k[3:] for k in T[f"{alpha}|{tau}|cert"] if k.startswith("ft|"))
            L += ["", "by fault type (success / unsafe / abstain):", "",
                  "| policy | " + " | ".join(f"{ft} (n={T[f'{alpha}|{tau}|cert']['ft|' + ft]['single_shot']['n']})"
                                             for ft in fts) + " |", "|---" * (len(fts) + 1) + "|"]
            for p in POL:
                L.append(f"| {NAME[p]} | " + " | ".join(
                    "{:.2f} / {:.3f} / {:.2f}".format(*(T[f"{alpha}|{tau}|{p}"]["ft|" + ft]["single_shot"][k]
                                                        for k in ("success", "unsafe", "abstain")))
                    for ft in fts) + " |")
            L += ["", "all faulted test episodes (natural size mix, n = "
                  f"{T[f'{alpha}|{tau}|cert']['all_faulted']['n']}): " + "; ".join(
                      f"{p} {f(T[f'{alpha}|{tau}|{p}']['all_faulted']['success'])} / "
                      f"{f(T[f'{alpha}|{tau}|{p}']['all_faulted']['unsafe'])}" for p in POL if p != "probe_all"), ""]
    L += ["## Time sensitivity (alpha 0.10): time per success (s) / mission success", "",
          "| variant | tau | " + " | ".join(POL) + " |", "|---" * (len(POL) + 2) + "|"]
    for var in ("reasm60", "reasm600", "parallel_probe"):
        for tau in ("0.5", "0.8"):
            L.append(f"| {var} | {tau} | " + " | ".join(
                f"{R['time_sensitivity'][f'{var}|{tau}|{p}']['time_per_success']:.0f} / "
                f"{R['time_sensitivity'][f'{var}|{tau}|{p}']['final_success']:.3f}" for p in POL) + " |")
    L += ["", "## Direct dock-sim validation (episodes whose every module was dock-simulated; alpha 0.10)", "",
          "| tau | policy | n eps | direct sim success | proxy p_dock(z) |", "|---|---|---|---|---|"]
    for k, v in R["direct_validation"].items():
        tau, p = k.split("|")
        L.append(f"| {tau} | {p} | {v['n']} | {f(v['direct_sim'])} | {f(v['proxy'])} |")
    D = json.loads((OUT / "demo_results.json").read_text())
    import numpy as np
    setups = [str(x) for x in np.load(OUT / "demo_preds.npz")["setups"]]
    for alpha in ("0.1", "0.05"):
        for tau in ("0.8", "0.5", "0.9"):
            L += ["", f"## D11 demo setups, alpha = {alpha}, tau = {tau} (256 sim trials each; fault module drawn "
                      "uniformly per run)", "",
                  "| setup | cert success / unsafe / abstain | bb | random | oracle | power cert>bb n=10/20/30 | "
                  "power cert>random n=10/20/30 |", "|---|---|---|---|---|---|---|"]
            for s in setups:
                def c(arm):
                    r = D[f"{s}|{alpha}|{tau}|{arm}"]
                    return f"{r['success']:.2f} / {r['unsafe']:.2f} / {r['abstain']:.2f}"
                pw = lambda o: "/".join(f"{D[f'{s}|{alpha}|{tau}|power_cert_vs_{o}|n{n}']:.2f}" for n in (10, 20, 30))
                L.append(f"| {s} | {c('cert')} | {c('bb')} | {c('random')} | {c('oracle')} | {pw('bb')} | "
                         f"{pw('random')} |")
    (OUT / "tables.md").write_text("\n".join(L) + "\n")
    print("wrote", OUT / "tables.md")


if __name__ == "__main__":
    main()
